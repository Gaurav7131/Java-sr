import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodHandles.Lookup;

public class Java15FeatHiddenClassesEx {
    public static void main(String[] args) throws Exception {
        Lookup lookup = MethodHandles.lookup();
        // // dummyByteCode:to evaluate whether hidden class gets used by other class's
        // bytecode
        byte[] dummyBytecode = new byte[] {
                (byte) 0xCA, (byte) 0xFE, (byte) 0xBA, (byte) 0xBE, 0x00, 0x00, 0x00, 0x37,
                0x00, 0x0A, 0x07, 0x00, 0x02, 0x01, 0x00, 0x05, 0x44, 0x75, 0x6D, 0x6D,
                0x79, 0x07, 0x00, 0x04, 0x01, 0x00, 0x10, 0x6A, 0x61, 0x76, 0x61, 0x2F,
                0x6C, 0x61, 0x6E, 0x67, 0x2F, 0x4F, 0x62, 0x6A, 0x65, 0x63, 0x74, 0x01,
                0x00, 0x06, 0x3C, 0x69, 0x6E, 0x69, 0x74, 0x3E, 0x01, 0x00, 0x03, 0x28,
                0x29, 0x56, 0x0C, 0x00, 0x05, 0x00, 0x06, 0x0A, 0x00, 0x03, 0x00, 0x07,
                0x01, 0x00, 0x04, 0x43, 0x6F, 0x64, 0x65, 0x00, 0x21, 0x00, 0x01, 0x00,
                0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x05, 0x00,
                0x06, 0x00, 0x01, 0x00, 0x09, 0x00, 0x00, 0x00, 0x11, 0x00, 0x01, 0x00,
                0x01, 0x00, 0x00, 0x00, 0x05, 0x2A, (byte) 0xB7, 0x00, 0x08, (byte) 0xB1,
                0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        };

        // Hidden class:cannt be used by others class's bc[],cannt get through
        // Class.get(),tied to define lifecycle without relying on classloader
        Lookup hiddenLookup = lookup.defineHiddenClass(dummyBytecode, true, Lookup.ClassOption.NESTMATE);
        Class<?> hiddenClass = hiddenLookup.lookupClass();

        System.out.println("Hidden ClassName:" + hiddenClass.getName());
        System.out.println("Is Hidden:" + hiddenClass.isHidden());

    }
}
